# Glyph slots: ASCII 32..95 by code, then the extra symbols at fixed codes
# the C side maps from UTF-8.
EXTRA = ['Ñ', '°', '▲', '▼', '►', '◄']


def rows(art):
    parts = art.split()
    assert len(parts) == 7, art
    out = []
    for p in parts:
        assert len(p) == 5, (art, p)
        out.append(sum(1 << (4 - i) for i, c in enumerate(p) if c == '#'))
    return out


def main():
    chars = [chr(c) for c in range(32, 96)] + EXTRA
    lines = ['/* SPDX-License-Identifier: MIT */',
             '/* Generated by tools/make_font5x7.py: do not edit. 5 x 7 glyphs, one byte',
             ' * per row, bit 4 the leftmost pixel. */',
             '#include "font5x7.h"', '',
             f'const uint8_t font5x7[{len(chars)}][7] = {{']
    for ch in chars:
        art = GLYPHS.get(ch, GLYPHS['?'])
        name = ch if ch.isprintable() and ord(ch) < 128 else f'U+{ord(ch):04X}'
        vals = ', '.join(f'0x{v:02X}' for v in rows(art))
        lines.append(f'    {{{vals}}}, /* {name.replace("*/", "* /")} */')
    lines += ['};', '']
    out = Path(__file__).resolve().parents[1] / 'firmware/esp32/core/font5x7.c'
    out.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{out}: {len(chars)} glyphs')


if __name__ == '__main__':
    main()
